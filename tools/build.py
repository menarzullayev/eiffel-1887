"""Build the standalone page.

src/index.html is the page body as published to a Claude Artifact (the Artifact host adds the
<!doctype>, <html>, <head> and <body> wrapper). This script adds that wrapper so the page also
works on its own: index.html at the repository root.

    python tools/build.py           write index.html
    python tools/build.py --check   exit 1 if index.html is missing or out of date
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "index.html"
OUT = ROOT / "index.html"

HEAD = """<!doctype html>
<html lang="uz">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!-- Generated by tools/build.py from src/index.html. Edit the source, then rebuild. -->
<style>
:root { color-scheme: light; padding-top: env(safe-area-inset-top, 0px); padding-bottom: env(safe-area-inset-bottom, 0px); }
body { margin: 0; font: 14px system-ui, -apple-system, "Segoe UI", sans-serif; }
img { max-width: 100%; }
[hidden] { display: none !important; }
</style>
"""


def build() -> str:
    src = SRC.read_text(encoding="utf-8")
    cut = src.find("<main")
    if cut < 0:
        raise SystemExit("src/index.html: no <main> element found")
    # <title>, font links and <style> go to <head>; the page itself goes to <body>.
    return HEAD + src[:cut].strip() + "\n</head>\n<body>\n" + src[cut:].strip() + "\n</body>\n</html>\n"


def main() -> int:
    page = build()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != page:
            print("index.html is out of date: run python tools/build.py", file=sys.stderr)
            return 1
        print("index.html is up to date")
        return 0
    OUT.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(page.encode('utf-8')) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
